using Microsoft.Extensions.DependencyInjection;
using RForge.Blazor;
using RForge.Blazor.AutoApi;
using RForge.Blazor.Events;

namespace Bundle;

// AutoApi: AddRForgeAutoApi() is emitted by the AutoApi generator.
public sealed record CounterValue(int Value);

[RForgeAutoApi]
public interface ICounter
{
    Task<CounterValue> GetAsync(CancellationToken cancellationToken = default);
}

[RForgeAutoApiClient(typeof(ICounter))]
public static partial class Clients { }

// Events: the partial property has no body unless the Events generator ran.
public sealed record Ping(int N) : IEvent;

public sealed record CountState(int Count) : IState<CountState>
{
    public static CountState Initial => new(0);
}

public partial class Probe : RfEventComponent
{
    // Components: a type from RForge.Blazor.Components.
    public RfDropDown<string>? Drop;

    [Subscribe] private void OnPing(Ping e) { }
    [UseState] private partial CountState Counter { get; }
}

public static class Wire
{
    public static void Register(IServiceCollection services)
    {
        services.AddRfForgeBlazorServices();   // RForge.Blazor.Components
        services.AddRForgeEvents();            // RForge.Blazor.Events
        services.AddRForgeAutoApi();           // generated by RForge.Blazor.AutoApi.Generator
    }
}
