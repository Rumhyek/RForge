using System.Linq;
using Microsoft.CodeAnalysis;

namespace RForge.Blazor.AutoApi.Generator
{
    internal static class ClientEmitter
    {
        private const string Runtime = "global::" + RuntimeSources.Namespace + ".RForgeAutoApiClientRuntime";
        private const string Hosting = "global::" + RuntimeSources.Namespace + ".RForgeAutoApiClientHosting";
        private const string FallbackJson = "RForgeAutoApiClientJson";

        public static void Emit(SourceProductionContext context, MarkerModel model)
        {
            if (model.Interfaces.Length == 0) return;

            context.AddSource("RForgeAutoApi.ClientRuntime.g.cs", RuntimeSources.Client);
            if (model.HasWebAssemblyHostEnvironment)
                context.AddSource("RForgeAutoApi.ClientHosting.g.cs", RuntimeSources.ClientHostBaseAddress);

            var usesFallback = model.Interfaces.SelectMany(i => i.Methods).Any(m =>
                (m.ResultJson is not null && m.ResultJson.TypeInfo is null) || m.Parameters.Any(p => p.QueryParse is null && p.Json.TypeInfo is null));
            if (usesFallback) context.AddSource("RForgeAutoApi.ClientJson.g.cs", RuntimeSources.JsonFallback(FallbackJson));

            var w = new CodeWriter();
            w.Line("// <auto-generated/>");
            w.Line("#nullable enable annotations");
            w.Line("#pragma warning disable CS1591");
            w.Line();

            if (model.Namespace is not null) w.Open($"namespace {model.Namespace}");
            w.Open($"static partial class {model.ClassName}");

            EmitAdd(w, model);
            foreach (var api in model.Interfaces) EmitClient(w, api);

            w.Close();
            if (model.Namespace is not null) w.Close();

            context.AddSource($"{model.Namespace}.{model.ClassName}.RForgeAutoApi.Client.g.cs".TrimStart('.'), w.ToString());
        }

        private static string TypeInfo(JsonTypeModel json)
            => json.TypeInfo ?? $"global::{RuntimeSources.Namespace}.{FallbackJson}.Get<{json.Type}>()";

        private static void EmitAdd(CodeWriter w, MarkerModel model)
        {
            const string http = "global::Microsoft.Extensions.DependencyInjection.HttpClientFactoryServiceCollectionExtensions";

            w.Line("/// <summary>");
            w.Line("/// Registers HttpClient implementations of every RForge Auto API interface and the named HttpClients they use.");
            w.Line("/// Returns the builder for the default client so handlers and settings can be added.");
            w.Line("/// </summary>");
            w.Open("public static global::Microsoft.Extensions.DependencyInjection.IHttpClientBuilder AddRForgeAutoApi(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");

            w.Line($"var __default = {http}.AddHttpClient(services, {ServerEmitter.Literal(model.DefaultClientName)});");
            if (model.HasWebAssemblyHostEnvironment) w.Line($"{Hosting}.UseHostBaseAddress(__default);");

            var otherNames = model.Interfaces.SelectMany(i => i.Methods).Select(m => m.ClientName)
                .Where(n => n != model.DefaultClientName).Distinct().OrderBy(n => n, System.StringComparer.Ordinal);
            foreach (var name in otherNames)
            {
                var add = $"{http}.AddHttpClient(services, {ServerEmitter.Literal(name)})";
                w.Line(model.HasWebAssemblyHostEnvironment ? $"{Hosting}.UseHostBaseAddress({add});" : $"{add};");
            }

            foreach (var api in model.Interfaces)
            {
                w.Line($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddScoped<{api.FullName}, {api.Identifier}AutoApiClient>(services);");
            }

            w.Line("return __default;");
            w.Close();
            w.Line();
        }

        private static void EmitClient(CodeWriter w, InterfaceModel api)
        {
            var name = api.Identifier + "AutoApiClient";
            w.Open($"private sealed class {name} : {api.FullName}");
            w.Line("private readonly global::System.Net.Http.IHttpClientFactory _httpClientFactory;");
            w.Line();
            w.Line($"public {name}(global::System.Net.Http.IHttpClientFactory httpClientFactory) => _httpClientFactory = httpClientFactory;");
            w.Line();

            foreach (var method in api.Methods)
            {
                var path = api.RoutePrefix.Length == 0 ? method.Route : api.RoutePrefix.TrimStart('/') + "/" + method.Route;
                var cancellationToken = method.CancellationTokenParameter ?? "default";

                w.Open($"async {method.ReturnType} {method.DeclaringInterface}.{ModelBuilder.EscapeIdentifier(method.Name)}({method.ParameterList})");
                w.Line($"var __http = _httpClientFactory.CreateClient({ServerEmitter.Literal(method.ClientName)});");

                string url;
                if (method.UsesQuery && method.Parameters.Length > 0)
                {
                    var query = string.Join(", ", method.Parameters.Select(p => $"({ServerEmitter.Literal(p.JsonName)}, (object?){p.Name})"));
                    url = $"{Runtime}.Url({ServerEmitter.Literal(path)}, {query})";
                }
                else
                {
                    url = ServerEmitter.Literal(path);
                }

                w.Line($"using var __request = new global::System.Net.Http.HttpRequestMessage({HttpMethod(method.HttpMethod)}, {url});");

                if (!method.UsesQuery && method.Parameters.Length > 0)
                {
                    w.Line("var __buffer = new global::System.Buffers.ArrayBufferWriter<byte>();");
                    w.Open("using (var __writer = new global::System.Text.Json.Utf8JsonWriter(__buffer))");
                    w.Line("__writer.WriteStartObject();");
                    foreach (var parameter in method.Parameters)
                    {
                        w.Line($"__writer.WritePropertyName({ServerEmitter.Literal(parameter.JsonName)});");
                        w.Line($"global::System.Text.Json.JsonSerializer.Serialize(__writer, {parameter.Name}, {TypeInfo(parameter.Json)});");
                    }
                    w.Line("__writer.WriteEndObject();");
                    w.Close();
                    w.Line($"__request.Content = {Runtime}.JsonBody(__buffer);");
                }

                if (method.HasResult)
                    w.Line($"return ({method.ResultType})(await {Runtime}.SendAsync(__http, __request, {TypeInfo(method.ResultJson!)}, {cancellationToken}).ConfigureAwait(false))!;");
                else
                    w.Line($"await {Runtime}.SendAsync(__http, __request, {cancellationToken}).ConfigureAwait(false);");

                w.Close();
                w.Line();
            }

            w.Close();
            w.Line();
        }

        private static string HttpMethod(string method) => method switch
        {
            "GET" => "global::System.Net.Http.HttpMethod.Get",
            "PUT" => "global::System.Net.Http.HttpMethod.Put",
            "PATCH" => "global::System.Net.Http.HttpMethod.Patch",
            "DELETE" => "global::System.Net.Http.HttpMethod.Delete",
            _ => "global::System.Net.Http.HttpMethod.Post",
        };
    }
}
