using System.Linq;
using Microsoft.CodeAnalysis;

namespace RForge.Blazor.AutoApi.Generator
{
    internal static class ServerEmitter
    {
        private const string Runtime = "global::" + RuntimeSources.Namespace + ".RForgeAutoApiServerRuntime";
        private const string FallbackJson = "RForgeAutoApiServerJson";
        private const string Task = "global::System.Threading.Tasks.Task";
        private const string HttpContext = "global::Microsoft.AspNetCore.Http.HttpContext";
        private const string AuthorizeData = "global::Microsoft.AspNetCore.Authorization.IAuthorizeData";

        public static void Emit(SourceProductionContext context, MarkerModel model)
        {
            if (model.Interfaces.Length == 0) return;

            context.AddSource("RForgeAutoApi.ServerRuntime.g.cs", RuntimeSources.Server);

            var usesFallback = model.Interfaces.SelectMany(i => i.Methods).Any(m =>
                (m.ResultJson is not null && m.ResultJson.TypeInfo is null) || m.Parameters.Any(p => !p.UsesQuery() && p.Json.TypeInfo is null));
            if (usesFallback) context.AddSource("RForgeAutoApi.ServerJson.g.cs", RuntimeSources.JsonFallback(FallbackJson));

            var w = new CodeWriter();
            w.Line("// <auto-generated/>");
            w.Line("#nullable enable annotations");
            w.Line("#pragma warning disable CS1591, CS8019");
            w.Line();
            w.Line("using global::Microsoft.AspNetCore.Builder;");
            w.Line("using global::Microsoft.AspNetCore.Http;");
            w.Line();

            if (model.Namespace is not null) w.Open($"namespace {model.Namespace}");

            w.Open($"static partial class {model.ClassName}");

            EmitAuthData(w, model);
            EmitMap(w, model);
            EmitAddServer(w, model);

            foreach (var api in model.Interfaces)
            {
                foreach (var method in api.Methods) EmitHandler(w, api, method);
            }

            foreach (var api in model.Interfaces.Where(NeedsDecorator)) EmitDecorator(w, api);

            w.Close();
            if (model.Namespace is not null) w.Close();

            context.AddSource($"{model.Namespace}.{model.ClassName}.RForgeAutoApi.Server.g.cs".TrimStart('.'), w.ToString());
        }

        private static bool UsesQuery(this ParameterModel parameter) => parameter.QueryParse is not null;

        private static bool NeedsDecorator(InterfaceModel api) => api.Methods.Any(m => m.RequiresAuthorization);

        private static string AuthField(MethodModel method) => "__rfAuth_" + method.Identifier;

        private static string TypeInfo(JsonTypeModel json)
            => json.TypeInfo ?? $"global::{RuntimeSources.Namespace}.{FallbackJson}.Get<{json.Type}>()";

        private static void EmitAuthData(CodeWriter w, MarkerModel model)
        {
            foreach (var method in model.Interfaces.SelectMany(i => i.Methods).Where(m => m.RequiresAuthorization))
            {
                w.Open($"private static readonly {AuthorizeData}[] {AuthField(method)} = new {AuthorizeData}[]");
                foreach (var auth in method.Auth)
                {
                    w.Line("new global::Microsoft.AspNetCore.Authorization.AuthorizeAttribute { "
                        + $"Policy = {Literal(auth.Policy)}, Roles = {Literal(auth.Roles)}, AuthenticationSchemes = {Literal(auth.AuthenticationSchemes)} }},");
                }
                w.Close(";");
                w.Line();
            }
        }

        private static void EmitMap(CodeWriter w, MarkerModel model)
        {
            w.Line("/// <summary>Maps every RForge Auto API endpoint. Conventions added to the returned group apply to all of them.</summary>");
            w.Open("public static global::Microsoft.AspNetCore.Routing.RouteGroupBuilder MapRForgeAutoApi(this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints)");
            w.Line("var __root = endpoints.MapGroup(\"\");");

            var groups = model.Interfaces.GroupBy(i => i.RoutePrefix).ToList();
            for (var g = 0; g < groups.Count; g++)
            {
                var prefix = groups[g].Key;
                var group = prefix.Length == 0 ? "__root" : $"__group{g}";
                if (prefix.Length > 0) w.Line($"var {group} = __root.MapGroup({Literal(prefix)});");

                foreach (var api in groups[g])
                {
                    foreach (var method in api.Methods)
                    {
                        w.Line($"{group}.MapMethods({Literal("/" + method.Route)}, new[] {{ {Literal(method.HttpMethod)} }}, new global::Microsoft.AspNetCore.Http.RequestDelegate(__rfHandle_{method.Identifier}))");
                        w.Indent();
                        w.Line($".WithName({Literal(method.EndpointName)})");
                        w.Line($".WithTags({Literal(api.Name)})");
                        if (method.AllowAnonymous) w.Line(".AllowAnonymous()");
                        else if (method.Auth.Length > 0) w.Line($".RequireAuthorization({AuthField(method)})");
                        foreach (var metadata in method.Metadata) w.Line($".WithMetadata({metadata})");
                        w.Line(";");
                        w.Outdent();
                    }
                }
            }

            w.Line("return __root;");
            w.Close();
            w.Line();
        }

        private static void EmitAddServer(CodeWriter w, MarkerModel model)
        {
            w.Line("/// <summary>");
            w.Line("/// Wraps your registrations of the RForge Auto API interfaces so [RfAuthorize] is enforced in Interactive Server mode.");
            w.Line("/// Call after registering the implementations.");
            w.Line("/// </summary>");
            w.Open("public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddRForgeAutoApiServer(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
            w.Line("global::Microsoft.Extensions.DependencyInjection.HttpServiceCollectionExtensions.AddHttpContextAccessor(services);");
            foreach (var api in model.Interfaces)
            {
                if (NeedsDecorator(api))
                    w.Line($"{Runtime}.Decorate<{api.FullName}>(services, static (inner, sp, ownsInner) => new {api.Identifier}AuthorizationDecorator(inner, sp, ownsInner));");
                else
                    w.Line($"{Runtime}.EnsureRegistered<{api.FullName}>(services);");
            }
            w.Line("return services;");
            w.Close();
            w.Line();
        }

        private static void EmitHandler(CodeWriter w, InterfaceModel api, MethodModel method)
        {
            w.Line($"private static {Task} __rfHandle_{method.Identifier}({HttpContext} httpContext)");
            w.Indent().Line($"=> {Runtime}.ExecuteAsync(httpContext, __rfInvoke_{method.Identifier});").Outdent();
            w.Line();

            w.Open($"private static async {Task} __rfInvoke_{method.Identifier}({HttpContext} httpContext)");
            w.Line("var cancellationToken = httpContext.RequestAborted;");

            var bodyParameters = method.Parameters.Where(p => !p.UsesQuery()).ToList();
            if (bodyParameters.Count > 0)
                w.Line($"using var __body = await {Runtime}.ReadBodyAsync(httpContext, cancellationToken).ConfigureAwait(false);");

            for (var i = 0; i < method.Parameters.Length; i++)
            {
                var parameter = method.Parameters[i];
                var missing = parameter.MissingValue ?? $"throw {Runtime}.Missing({Literal(parameter.JsonName)})";
                if (parameter.UsesQuery())
                {
                    var parse = string.Format(parameter.QueryParse!, "__raw");
                    w.Line($"string? __q{i} = httpContext.Request.Query[{Literal(parameter.JsonName)}];");
                    w.Line($"{parameter.Type} __p{i} = __q{i} is null ? {missing} : {Runtime}.ParseQuery(__q{i}, {Literal(parameter.JsonName)}, static __raw => {parse});");
                }
                else
                {
                    w.Line($"{parameter.Type} __p{i} = __body.TryGet({Literal(parameter.JsonName)}, out var __e{i}) ? {Runtime}.Deserialize(__e{i}, {Literal(parameter.JsonName)}, {TypeInfo(parameter.Json)}) : {missing};");
                }
            }

            w.Line($"var __service = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{api.FullName}>(httpContext.RequestServices);");
            var call = $"(({method.DeclaringInterface})__service).{ModelBuilder.EscapeIdentifier(method.Name)}({method.ServerArgumentList})";
            if (method.HasResult)
            {
                w.Line($"var __result = await {call}.ConfigureAwait(false);");
                w.Line($"await {Runtime}.WriteJsonAsync(httpContext, __result, {TypeInfo(method.ResultJson!)}, cancellationToken).ConfigureAwait(false);");
            }
            else
            {
                w.Line($"await {call}.ConfigureAwait(false);");
                w.Line("httpContext.Response.StatusCode = 204;");
            }
            w.Close();
            w.Line();
        }

        private static void EmitDecorator(CodeWriter w, InterfaceModel api)
        {
            var name = api.Identifier + "AuthorizationDecorator";
            w.Open($"private sealed class {name} : {api.FullName}, global::System.IDisposable, global::System.IAsyncDisposable");
            w.Line($"private readonly {api.FullName} _inner;");
            w.Line("private readonly global::System.IServiceProvider _services;");
            w.Line("private readonly bool _ownsInner;");
            w.Line();
            w.Open($"public {name}({api.FullName} inner, global::System.IServiceProvider services, bool ownsInner)");
            w.Line("_inner = inner;");
            w.Line("_services = services;");
            w.Line("_ownsInner = ownsInner;");
            w.Close();
            w.Line();

            foreach (var method in api.Methods)
            {
                var methodName = ModelBuilder.EscapeIdentifier(method.Name);
                var call = $"(({method.DeclaringInterface})_inner).{methodName}({method.ArgumentList})";
                var signature = $"{method.ReturnType} {method.DeclaringInterface}.{methodName}({method.ParameterList})";

                if (!method.RequiresAuthorization)
                {
                    w.Line($"{signature} => {call};");
                    w.Line();
                    continue;
                }

                w.Open($"async {signature}");
                w.Line($"await {Runtime}.AuthorizeAsync(_services, {AuthField(method)}).ConfigureAwait(false);");
                w.Line(method.HasResult ? $"return await {call}.ConfigureAwait(false);" : $"await {call}.ConfigureAwait(false);");
                w.Close();
                w.Line();
            }

            w.Open("public void Dispose()");
            w.Line("if (_ownsInner && _inner is global::System.IDisposable disposable) disposable.Dispose();");
            w.Close();
            w.Line();
            w.Open("public global::System.Threading.Tasks.ValueTask DisposeAsync()");
            w.Line("if (_ownsInner && _inner is global::System.IAsyncDisposable asyncDisposable) return asyncDisposable.DisposeAsync();");
            w.Line("if (_ownsInner && _inner is global::System.IDisposable disposable) disposable.Dispose();");
            w.Line("return default;");
            w.Close();

            w.Close();
            w.Line();
        }

        internal static string Literal(string? value)
            => value is null ? "null" : Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);
    }
}
