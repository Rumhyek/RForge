using System.Diagnostics.CodeAnalysis;
using Microsoft.AspNetCore.Components;

namespace RForge.Blazor.Bus;

/// <summary>
/// Base class for components that use the bus. Handles subscription, re-rendering, thread marshaling,
/// error routing and cleanup.
/// </summary>
/// <remarks>
/// Subscriptions are registered in the first <see cref="SetParametersAsync"/>, after parameters and cascading
/// values are assigned and before <c>OnInitialized</c> runs, so they don't depend on calls to <c>base</c>.
/// Override <see cref="DisposeAsyncCore"/> for your own cleanup instead of implementing <see cref="IDisposable"/>.
/// </remarks>
public abstract class BusComponentBase : ComponentBase, IAsyncDisposable
{
    private readonly CancellationTokenSource _disposalCts = new();
    private readonly List<IDisposable> _registrations = [];
    private IBusScope? _scope;
    private bool _registered;
    private bool _disposed;

    /// <summary>Initializes a new instance.</summary>
    [DynamicDependency(DynamicallyAccessedMemberTypes.NonPublicProperties, typeof(BusComponentBase))]
    protected BusComponentBase()
    {
    }

    [CascadingParameter]
    private IBusScope? CascadedScope { get; set; }

    [Inject]
    private IBus RootBus { get; set; } = default!;

    /// <summary>The nearest enclosing scope, or the root bus if there is none.</summary>
    /// <exception cref="InvalidOperationException">Accessed before the component received its first parameters.</exception>
    protected IBusScope Scope => _scope ?? throw new InvalidOperationException(
        "The bus scope is not available until the component has received its parameters.");

    /// <summary>Cancelled when the component is disposed.</summary>
    protected CancellationToken DisposalToken => _disposalCts.Token;

    /// <summary>
    /// Registers event handlers and state handles. Generated by the RForge.Blazor.Bus source generator from
    /// <see cref="SubscribeAttribute"/> and <see cref="UseStateAttribute"/>, or overridden by hand.
    /// </summary>
    protected virtual void RegisterSubscriptions(SubscriptionBuilder builder)
    {
    }

    /// <summary>Publishes an event relative to <see cref="Scope"/>.</summary>
    protected ValueTask PublishAsync<TEvent>(TEvent evt, Route route = default, CancellationToken cancellationToken = default)
        where TEvent : IEvent =>
        Scope.PublishAsync(evt, route, cancellationToken);

    /// <summary>
    /// Resolves the store for <typeparamref name="TState"/> relative to <see cref="Scope"/>. Use it to write, or for a
    /// one-off read; for reactive reads use <see cref="UseStateAttribute"/> or a <see cref="StateHandle{TState}"/>.
    /// </summary>
    protected IStateStore<TState> State<TState>(ScopeTarget at = default) where TState : IState<TState> =>
        Scope.State<TState>(at);

    /// <inheritdoc />
    public override Task SetParametersAsync(ParameterView parameters)
    {
        if (_registered)
        {
            return base.SetParametersAsync(parameters);
        }

        parameters.SetParameterProperties(this);
        _registered = true;
        _scope = CascadedScope ?? RootBus;

        var builder = new SubscriptionBuilder(this);
        try
        {
            RegisterSubscriptions(builder);
        }
        finally
        {
            builder.Complete();
        }

        // Parameters are already assigned; run the normal lifecycle (OnInitialized, OnParametersSet, render).
        return base.SetParametersAsync(ParameterView.Empty);
    }

    /// <summary>Override to release resources. Called once, after bus subscriptions are released.</summary>
    protected virtual ValueTask DisposeAsyncCore() => ValueTask.CompletedTask;

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        if (_disposed)
        {
            return;
        }

        _disposed = true;
        _disposalCts.Cancel();

        foreach (var registration in _registrations)
        {
            registration.Dispose();
        }

        _registrations.Clear();

        try
        {
            await DisposeAsyncCore();
        }
        finally
        {
            _disposalCts.Dispose();
            GC.SuppressFinalize(this);
        }
    }

    // ── Infrastructure used by SubscriptionBuilder ───────────────────────

    internal IBusScope BusScopeInternal => Scope;

    internal void Track(IDisposable registration) => _registrations.Add(registration);

    internal ValueTask DeliverAsync<TEvent>(
        Func<TEvent, CancellationToken, ValueTask> handler,
        TEvent evt,
        bool render,
        CancellationToken publishToken)
    {
        if (_disposed)
        {
            return ValueTask.CompletedTask;
        }

        return new ValueTask(InvokeAsync(async () =>
        {
            if (_disposed)
            {
                return;
            }

            var disposalToken = _disposalCts.Token;
            using var linked = publishToken.CanBeCanceled
                ? CancellationTokenSource.CreateLinkedTokenSource(publishToken, disposalToken)
                : null;

            try
            {
                await handler(evt, linked?.Token ?? disposalToken);
            }
            catch (OperationCanceledException) when (disposalToken.IsCancellationRequested)
            {
                return; // The component went away; not an error.
            }
            catch (OperationCanceledException) when (publishToken.IsCancellationRequested)
            {
                throw; // Surfaces to the publisher.
            }
            catch (Exception ex)
            {
                if (!_disposed)
                {
                    await DispatchExceptionAsync(ex);
                }

                return;
            }

            if (render && !_disposed)
            {
                StateHasChanged();
            }
        }));
    }

    internal void ScheduleRender(Func<bool>? shouldRender = null)
    {
        if (_disposed)
        {
            return;
        }

        InvokeAsync(() =>
        {
            if (!_disposed && (shouldRender is null || shouldRender()))
            {
                StateHasChanged();
            }
        }).Observe();
    }
}
